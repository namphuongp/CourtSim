import { SCORING_RUBRIC } from '../src/data/scoringRubric.js';
import assert from 'node:assert/strict';
import test from 'node:test';
import http from 'node:http';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';

// Chạy tùy chọn trên DB riêng; tuyệt đối không dùng/drop DB của ứng dụng.
test('luồng HTTP với MongoDB: xác thực, lượt nguyên tử, gửi trùng, khóa, chấm điểm và lịch sử', {skip: !process.env.COURTSIM_TEST_MONGO_URI, timeout:60000}, async (t) => {
  const databaseName = `courtsim_test_${randomUUID().replaceAll('-','')}`;
  let malformed = false;
  let calls = 0;
  const ai = http.createServer(async (req,res) => {
    let body = ''; for await (const chunk of req) body += chunk;
    calls++;
    const prompt = JSON.parse(body).messages[0].content;
    const context = JSON.parse(prompt.split('<UNTRUSTED_CASE_AND_LAW_DATA_JSON>')[1].split('</UNTRUSTED_CASE_AND_LAW_DATA_JSON>')[0]);
    const user = context.recentProceedings.findLast((r)=>r.speaker_type==='user');
    const fact_analysis = {established_facts:['Có hợp đồng vay.'],learner_claims:[],inferences:[],missing_facts:['Chưa có biên nhận']};
    const rubric_scores = {legal_knowledge:70,reasoning:80,evidence_use:90,courtroom_skill:60};
    const payload = prompt.includes('unassessedReasons') ? {verdict:'Đạt yêu cầu thực hành',score:1,criteria:SCORING_RUBRIC.groups.flatMap(g=>g.items.map(i=>({id:i.id,score:i.max*0.8,reason:'Có liên hệ hồ sơ',strength:'Bám chứng cứ',improvement:'Giải thích chứng cứ',record_id:user.record_id,quote:user.text.slice(0,20)}))),rubric_scores,feedback:'Lập luận có chứng cứ',improvement_suggestions:'Giải thích giới hạn lời khai',fact_analysis,citation_ids:[],rubric_feedback:Object.fromEntries(Object.keys(rubric_scores).map(key=>[key,{reason:'Có liên hệ hồ sơ',strength:'Nêu đúng hợp đồng',improvement:'Làm rõ chứng cứ thanh toán',record_id:user.record_id,quote:user.text.slice(0,20)}]))} : {content:'Hồ sơ có hợp đồng, nhưng lời khai trả tiền cần được chứng minh. Bạn đối chiếu lời khai này với chứng cứ nào?',fact_analysis,citation_ids:[]};
    await new Promise(resolve=>setTimeout(resolve,100));
    res.setHeader('Content-Type','application/json');
    res.end(JSON.stringify({choices:[{message:{content:malformed ? 'null' : JSON.stringify(payload)}}]}));
  });
  await new Promise(resolve=>ai.listen(0,'127.0.0.1',resolve));
  process.env.JWT_SECRET='integration-test-secret-for-isolated-db-only';
  process.env.GEMINI_API_KEY='';
  process.env.LEGAL_ONLINE_LOOKUP='false';
  process.env.AI_BASE_URL=`http://127.0.0.1:${ai.address().port}`;
  const {createApp}=await import('../src/app.js');
  const {Case,User,AiPersonal,SimulationSession,CourtRecord,TrialResult}=await import('../src/models/index.js');
  let api;
  t.after(async()=>{
    if(api) await new Promise(resolve=>api.close(resolve));
    await new Promise(resolve=>ai.close(resolve));
    if(mongoose.connection.name===databaseName && /^courtsim_test_[a-f0-9]{32}$/.test(databaseName)) await mongoose.connection.dropDatabase();
    await mongoose.disconnect();
  });
  await mongoose.connect(process.env.COURTSIM_TEST_MONGO_URI,{dbName:databaseName,serverSelectionTimeoutMS:5000});
  await Promise.all([User.init(),SimulationSession.init(),TrialResult.init()]);
  await AiPersonal.insertMany(['judge','prosecutor','evaluator'].map(role_name=>({role_name,system_prompt:'Bám hồ sơ và giữ đúng vai.',model_id:'test',temperature:0.1})));
  const courtCase=await Case.create({title:'Hồ sơ kiểm thử',category:'dân sự',summary:'Tranh chấp vay',full_document:'Có hợp đồng vay. Chưa có biên nhận trả tiền.'});
  api=createApp().listen(0,'127.0.0.1');
  await new Promise(resolve=>api.once('listening',resolve));
  const base=`http://127.0.0.1:${api.address().port}/api`;
  async function request(path,{method='GET',body,token}={}) {
    const response=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},...(body!==undefined?{body:JSON.stringify(body)}:{})});
    return {status:response.status,body:await response.json()};
  }
  assert.equal((await request('/auth/register',{method:'POST',body:{full_name:{x:1},email:[],password:'12345678'}})).status,400);
  const password=randomUUID();
  for(const email of ['one@test.local','two@test.local']) assert.equal((await request('/auth/register',{method:'POST',body:{full_name:'Người kiểm thử',email,password}})).status,201);
  const login=await request('/auth/login',{method:'POST',body:{email:'one@test.local',password}});
  const token=login.body.token;
  const other=(await request('/auth/login',{method:'POST',body:{email:'two@test.local',password}})).body.token;
  const setup={case_id:String(courtCase._id),user_court_role:'defense_lawyer',difficulty:'beginner',case_event_date:'2025-01-01',request_id:randomUUID()};
  const creations=await Promise.all([request('/v1/sessions',{method:'POST',token,body:setup}),request('/v1/sessions',{method:'POST',token,body:setup})]);
  assert.deepEqual(creations.map(r=>r.status),[201,201]);
  const id=creations[0].body.data.session._id;
  assert.equal(creations[1].body.data.session._id,id);
  assert.equal(await SimulationSession.countDocuments(),1);
  assert.equal((await request(`/v1/sessions/${id}`,{token:other})).status,404);
  assert.equal((await request(`/v1/sessions/${id}/legal-basis`,{token:other})).status,404);
  const legalBasis=await request(`/v1/sessions/${id}/legal-basis`,{token});
  assert.equal(legalBasis.status,200);
  assert.equal(legalBasis.body.data.legal_assessment_available,false);
  assert.ok(legalBasis.body.data.warnings.some((warning)=>warning.includes('Chưa xác minh được')));
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token:other,body:{content:'Lập luận không được phép'}})).status,404);
  assert.equal((await request(`/v1/sessions/${id}/complete`,{method:'POST',token})).status,400);
  malformed=true;
  const turn={content:'Tôi căn cứ hợp đồng trong hồ sơ để đề nghị kiểm tra chứng cứ thanh toán.',request_id:randomUUID(),expected_turn_count:0};
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:turn})).status,502);
  assert.equal((await request(`/v1/sessions/${id}/records`,{token})).body.data.length,1);
  malformed=false;
  const results=await Promise.all([request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:turn}),request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:turn})]);
  assert.equal(results.filter(r=>r.status===201).length,1);
  assert.equal(results.filter(r=>r.status===409).length,1);
  const beforeReplay=calls;
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:turn})).status,200);
  assert.equal(calls,beforeReplay);
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:{...turn,content:'Thay đổi nội dung đã gửi'}})).status,409);
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:{...turn,request_id:randomUUID()}})).status,409);
  const records=(await request(`/v1/sessions/${id}/records`,{token})).body.data;
  assert.equal(records.length,4);
  assert.equal(records[1].request_id,turn.request_id);
  malformed=true;
  assert.equal((await request(`/v1/sessions/${id}/complete`,{method:'POST',token})).status,502);
  assert.equal((await request(`/v1/sessions/${id}`,{token})).body.data.status,'ongoing');
  assert.equal((await request(`/v1/sessions/${id}/result`,{token})).status,404);
  malformed=false;
  const completions=await Promise.all([request(`/v1/sessions/${id}/complete`,{method:'POST',token}),request(`/v1/sessions/${id}/complete`,{method:'POST',token})]);
  const result=completions.find(r=>r.status===200);
  assert.equal(completions.filter(r=>r.status===409).length,1);
  assert.equal(result.status,200);
  assert.equal(result.body.data.score,80);
  const beforeComplete=calls;
  assert.equal((await request(`/v1/sessions/${id}/complete`,{method:'POST',token})).body.data.score,80);
  assert.equal(calls,beforeComplete);
  assert.equal(result.body.data.assessed_max,48);
  assert.equal(result.body.data.criteria.length,6);
  assert.deepEqual((await request(`/v1/sessions/${id}/result`,{token})).body.data,result.body.data);
  assert.equal((await request(`/v1/sessions/${id}/messages`,{method:'POST',token,body:{...turn,request_id:randomUUID(),expected_turn_count:1}})).status,409);
  assert.equal((await request(`/v1/sessions/${id}/result`,{token:other})).status,404);
  const list=(await request('/v1/sessions',{token})).body.data;
  assert.equal(list[0].status,'completed'); assert.equal(list[0].result.score,80); assert.equal(list[0].operation,undefined);
  const legacy=await SimulationSession.create({user_id:login.body.user.id,case_id:courtCase._id,user_court_role:'defense_lawyer',status:'completed'});
  await CourtRecord.create({session_id:legacy._id,sender_type:'user',sender_name:'Luật sư',content:'Biên bản phiên cũ'});
  await TrialResult.create({session_id:legacy._id,score:50,verdict:'Kết quả cũ',feedback:'Nhận xét cũ',improvement_suggestions:'Góp ý cũ'});
  assert.equal((await request(`/v1/sessions/${legacy._id}/result`,{token})).body.data.score,50);
  assert.equal((await request(`/v1/sessions/${legacy._id}/records`,{token})).body.data[0].content,'Biên bản phiên cũ');
  const undated=await SimulationSession.create({user_id:login.body.user.id,case_id:courtCase._id,user_court_role:'defense_lawyer'});
  assert.equal((await request(`/v1/sessions/${undated._id}`,{method:'PATCH',token:other,body:{case_event_date:'2025-01-01'}})).status,404);
  assert.equal((await request(`/v1/sessions/${undated._id}`,{method:'PATCH',token,body:{case_event_date:'2025-02-29'}})).status,400);
  assert.equal((await request(`/v1/sessions/${undated._id}`,{method:'PATCH',token,body:{case_event_date:'2025-01-01'}})).status,200);
  assert.equal((await request(`/v1/sessions/${undated._id}`,{method:'PATCH',token,body:{case_event_date:'2024-01-01'}})).status,409);
  await SimulationSession.updateOne({_id:undated._id},{$set:{turn_count:20}});
  assert.equal((await request(`/v1/sessions/${undated._id}/messages`,{method:'POST',token,body:{...turn,request_id:randomUUID(),expected_turn_count:20}})).body.error.code,'TURN_LIMIT');
  await User.updateOne({_id:login.body.user.id},{$set:{status:'banned'}});
  const {sampleLandCase}=await import('../src/data/sampleLandCase.js');
  const historical=await Case.create(sampleLandCase);
  const historicalSetup={...setup,case_id:String(historical._id),request_id:randomUUID()};
  assert.equal((await request('/v1/sessions',{method:'POST',token:other,body:historicalSetup})).body.error.code,'CASE_DATE_MISMATCH');
  const historicalSession=await request('/v1/sessions',{method:'POST',token:other,body:{...historicalSetup,case_event_date:sampleLandCase.reference_date}});
  assert.equal(historicalSession.status,201);
  const historicalDetail=(await request(`/v1/sessions/${historicalSession.body.data.session._id}`,{token:other})).body.data;
  assert.equal(historicalDetail.case_id.source_url,sampleLandCase.source_url);
  assert.ok(historicalDetail.legal_coverage_warnings.includes(sampleLandCase.legal_scope_note));
  assert.ok(!historicalDetail.case_id.full_document.includes('114,85'));
  assert.equal((await request('/v1/sessions',{token})).status,403);
});
